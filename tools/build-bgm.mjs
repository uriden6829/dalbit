// Builds Dalbit's background-music presets with the Live Studio engine (vendored in app/vendor/adaptive-music.js)
// and writes the static AudioWorklet file the app loads (so the CSP can stay `script-src 'self'`).
//   node tools/build-bgm.mjs          -> app/content/bgm-presets.js + app/vendor/am-worklet.js + loudness report
//
// Every preset has the same controls, which app/js/lib/bgm.js drives from what she is doing:
//   Focus  0..1  0 = browsing, 0.5 = practising, 1 = listening/speaking (band thins out, muffles, almost silent)
//   Story  on/off  reading a webtoon (more space and warmth)
//   events: "Correct" (tiny chime), "Lesson done" (rising flourish)
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const RUNTIME = new URL('../app/vendor/adaptive-music.js', import.meta.url);
vm.runInThisContext(readFileSync(RUNTIME, 'utf8'), { filename: 'adaptive-music.js' });
const AM = globalThis.AdaptiveMusic;
const DM = AM.DM, ST = DM.STUDIO;

let uid = 0;
DM.uid = (p) => `${p || 'x'}_${(++uid).toString(36)}`; // deterministic ids -> stable diffs

function param(P, o) { const p = { id: DM.uid('par'), links: [], ...o }; P.params.push(p); return p; }
const curve = (p, target, points) => p.links.push({ id: DM.uid('lnk'), target, points });
const event = (P, name, actions) => P.events.push({ id: DM.uid('evt'), name, key: '', actions });

function preset({ id, name, ko, desc, genre, seed, changes = {}, tweak }) {
  const P = ST.blankPreset(name);
  P.seed = seed;
  P.notes = desc;
  const r = ST.styleFromGenre(genre, name, P, seed);
  r.instruments.forEach((i) => P.instruments.push(i));
  Object.assign(r.style, { entry: { mode: 'blend', bars: 2, fill: false, crash: false } }, changes);
  P.styles.push(r.style);
  P.main = r.style.id;
  tweak?.(P, r.style);
  const focus = param(P, { name: 'Focus', type: 'slider', min: 0, max: 1, step: 0.01, def: 0.3, smooth: 1.8, desc: 'How much she needs to concentrate.' });
  curve(focus, 'g:energy', [[0, 0.05], [0.5, -0.12], [1, -0.5]]);
  curve(focus, 'g:volume', [[0, 1], [0.5, 0.78], [0.85, 0.32], [1, 0.14]]);
  curve(focus, 'g:muffle', [[0, 0], [0.6, 0.1], [1, 0.6]]);
  curve(focus, 'g:brightness', [[0, 0], [1, -0.35]]);
  curve(focus, 'g:speed', [[0, 1], [1, 0.94]]);
  const story = param(P, { name: 'Story', type: 'switch', def: 0, smooth: 2, desc: 'Reading a webtoon.' });
  curve(story, 'g:space', [[0, 0], [1, 0.2]]);
  curve(story, 'g:energy', [[0, 0], [1, 0.08]]);
  curve(story, 'g:color', [[0, 0], [1, 0.15]]);
  event(P, 'Correct', [{ do: 'cue', cue: 'chime', sound: 'celesta', when: 'now', volume: 0.32 }]);
  event(P, 'Lesson done', [{ do: 'cue', cue: 'rise', sound: 'harp', when: 'beat', volume: 0.5 }]);
  return { id, name, ko, desc, preset: DM.normalizePreset(P) };
}

const LIST = [
  preset({ id: 'moonlit', name: 'Moonlit Study', ko: '달빛 서재', desc: 'Soft lo-fi piano and a dusty beat by the window.',
    genre: 'lofi', seed: 11, changes: { tempo: 74, energy: 0.32, key: 'Eb' } }),
  preset({ id: 'cafe', name: 'Rainy Café', ko: '비 오는 카페', desc: 'Nylon guitar and flute, a slow bossa for a wet evening.',
    genre: 'bossa', seed: 23, changes: { tempo: 104, energy: 0.3, space: 0.45, bright: 0.45 } }),
  preset({ id: 'bakery', name: 'Witch’s Bakery', ko: '마녀의 빵집', desc: 'A light-footed little waltz for warm bread and errands.',
    genre: 'waltz', seed: 37, changes: { tempo: 126, energy: 0.32, key: 'F', space: 0.4 } }),
  preset({ id: 'journey', name: 'Long Journey', ko: '먼 여행길', desc: 'Harp, whistle and open air — a road through hills and old ruins.',
    genre: 'ambient', seed: 41, changes: { tempo: 76, energy: 0.3, key: 'D', scale: 'major' } }),
  preset({ id: 'lullaby', name: 'Starlight Lullaby', ko: '별빛 자장가', desc: 'Music box and harp, for late nights.',
    genre: 'lullaby', seed: 53, changes: { tempo: 70, energy: 0.18 } }),
];

// Loudness check (offline render) so no preset is much louder than another.
const db = (x) => (20 * Math.log10(Math.max(1e-9, x))).toFixed(1);
for (const p of LIST) {
  const line = [];
  for (const [label, focus] of [['browse', 0], ['study', 0.5], ['listen', 1]]) {
    const r = AM.render(p.preset, 12, { sampleRate: 22050, params: { [p.preset.params[0].id]: focus } });
    let sum = 0, peak = 0;
    for (let i = 0; i < r.L.length; i++) { const v = (r.L[i] + r.R[i]) / 2; sum += v * v; peak = Math.max(peak, Math.abs(r.L[i]), Math.abs(r.R[i])); }
    line.push(`${label} rms ${db(Math.sqrt(sum / r.L.length))} dB peak ${db(peak)}`);
  }
  console.log(`${p.id.padEnd(8)} ${line.join(' | ')}`);
}

const out = `// Generated by tools/build-bgm.mjs from Live Studio genre templates. Do not edit by hand: change the script and rebuild.\n` +
  `export const BGM_PRESETS = ${JSON.stringify(LIST)};\n`;
writeFileSync(new URL('../app/content/bgm-presets.js', import.meta.url), out);
writeFileSync(new URL('../app/vendor/am-worklet.js', import.meta.url), `// Generated by tools/build-bgm.mjs (Live Studio engine as an AudioWorklet module).\n${AM.engineSource()}`);
console.log('wrote app/content/bgm-presets.js and app/vendor/am-worklet.js');
